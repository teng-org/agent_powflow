function endpoint(id, name, method, baseKey, path, options = {}) {
  return {
    id,
    name,
    method,
    baseKey,
    path,
    headers: options.public ? {} : { Authorization: 'Bearer <admin-token>' },
    pathParams: options.pathParams || {},
    queryParams: options.queryParams || {},
    body: options.body ?? null,
    summary: options.summary || '',
  }
}


param(
  [string]$OutputPath = ".env.production",
  [switch]$Force
)

$ErrorActionPreference = "Stop"

$workspaceRoot = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot "../.."))
$target = if ([System.IO.Path]::IsPathRooted($OutputPath)) {
  [System.IO.Path]::GetFullPath($OutputPath)
} else {
  [System.IO.Path]::GetFullPath((Join-Path $workspaceRoot $OutputPath))
}
$workspacePrefix = $workspaceRoot.TrimEnd([System.IO.Path]::DirectorySeparatorChar) + [System.IO.Path]::DirectorySeparatorChar
if (-not $target.StartsWith($workspacePrefix, [System.StringComparison]::OrdinalIgnoreCase)) {
  throw "OutputPath must stay inside workspace: $workspaceRoot"
}
if ((Test-Path -LiteralPath $target) -and -not $Force) {
  throw "Refusing to overwrite existing production env file. Use -Force only after verifying the exact target: $target"
}

function New-RandomBytes {
  param([int]$Count)
  $bytes = New-Object byte[] $Count
  $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
  try { $rng.GetBytes($bytes) } finally { $rng.Dispose() }
  return $bytes
}

function New-UrlSafeSecret {
  param([int]$Bytes = 32, [switch]$KeepPadding)
  $value = [Convert]::ToBase64String((New-RandomBytes -Count $Bytes)).Replace('+', '-').Replace('/', '_')
  if (-not $KeepPadding) { $value = $value.TrimEnd('=') }
  return $value
}

